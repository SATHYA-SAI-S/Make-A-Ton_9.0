import React, { useEffect, useState } from 'react';
import type { billingApi } from '../api';
import type { BillingRun, BillingRunItem } from '../types';
import type { Card, Badge, Modal, StatCard } from '../components';

export const BillingControlPage: React.FC = () => {
  const [runs, setRuns] = useState<BillingRun[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  // Trigger Run State
  const [asOfDate, setAsOfDate] = useState(new Date().toISOString().split('T')[0]);
  const [isExecuting, setIsExecuting] = useState(false);

  // Run Details Modal State
  const [selectedRun, setSelectedRun] = useState<(BillingRun & { items: BillingRunItem[] }) | null>(null);
  const [loadingDetails, setLoadingDetails] = useState(false);

  const loadRuns = async () => {
    try {
      setLoading(true);
      const res = await billingApi.getRuns();
      setRuns(res.items || []);
      setError(null);
    } catch (err: any) {
      setError(err.message || 'Failed to fetch billing runs');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadRuns();
  }, []);

  const executeRun = async (dryRun: boolean) => {
    try {
      setIsExecuting(true);
      const result = await billingApi.runBilling({
        as_of: asOfDate,
        dry_run: dryRun
      });
      alert(
        `Billing ${dryRun ? 'Dry Run' : 'Execution'} Completed!\n\n` +
        `Status: ${result.status}\n` +
        `Subscriptions Checked: ${result.subscriptions_checked}\n` +
        `Invoices Created: ${result.invoices_created}\n` +
        `Failures: ${result.failures}`
      );
      await loadRuns();
    } catch (err: any) {
      alert(`Billing execution error: ${err.message}`);
    } finally {
      setIsExecuting(false);
    }
  };

  const openRunDetails = async (runId: string) => {
    try {
      setLoadingDetails(true);
      const details = await billingApi.getRun(runId);
      setSelectedRun(details);
    } catch (err: any) {
      alert(`Failed to load run details: ${err.message}`);
    } finally {
      setLoadingDetails(false);
    }
  };

  const totalInvoicesGen = runs.reduce((acc, r) => acc + (r.invoices_created || 0), 0);
  const lastRun = runs[0];

  return (
    <div style={{ padding: '24px', maxWidth: '1200px', margin: '0 auto', fontFamily: 'sans-serif' }}>
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '24px' }}>
        <div>
          <h1 style={{ margin: 0, fontSize: '24px', fontWeight: 700, color: '#111827' }}>Billing Engine Control</h1>
          <p style={{ margin: '4px 0 0 0', color: '#6B7280' }}>
            Advisory-locked recurring billing run automation, missed runs detector, and audit log
          </p>
        </div>
      </div>

      {error && (
        <div style={{ padding: '12px 16px', backgroundColor: '#FEE2E2', color: '#991B1B', borderRadius: '6px', marginBottom: '20px' }}>
          {error}
        </div>
      )}

      {/* Metrics Row */}
      <div style={{ display: 'flex', gap: '16px', marginBottom: '24px', flexWrap: 'wrap' }}>
        <StatCard title="Total Billing Runs" value={runs.length} subtitle="Recorded historical runs" />
        <StatCard title="Total Invoices Created" value={totalInvoicesGen} subtitle="Generated by billing engine" variant="success" />
        <StatCard
          title="Latest Run Status"
          value={lastRun ? lastRun.status : 'N/A'}
          subtitle={lastRun ? new Date(lastRun.started_at).toLocaleString() : 'No runs yet'}
          variant={lastRun?.status === 'COMPLETED' ? 'success' : 'warning'}
        />
      </div>

      {/* Trigger Run Control Card */}
      <Card title="Trigger Billing Engine Execution" subtitle="Run recurring billing across all active billable subscriptions">
        <div style={{ display: 'flex', alignItems: 'center', gap: '16px', flexWrap: 'wrap' }}>
          <div>
            <label style={{ display: 'block', fontSize: '13px', fontWeight: 600, color: '#374151', marginBottom: '4px' }}>
              As Of Date
            </label>
            <input
              type="date"
              value={asOfDate}
              onChange={(e) => setAsOfDate(e.target.value)}
              style={{ padding: '8px 12px', border: '1px solid #D1D5DB', borderRadius: '6px' }}
            />
          </div>

          <div style={{ display: 'flex', gap: '12px', marginTop: '22px' }}>
            <button
              onClick={() => executeRun(false)}
              disabled={isExecuting}
              style={{
                backgroundColor: '#2563EB',
                color: '#FFFFFF',
                border: 'none',
                borderRadius: '6px',
                padding: '10px 20px',
                fontWeight: 600,
                cursor: isExecuting ? 'not-allowed' : 'pointer'
              }}
            >
              {isExecuting ? 'Running...' : 'Run Billing Engine Now'}
            </button>
            <button
              onClick={() => executeRun(true)}
              disabled={isExecuting}
              style={{
                backgroundColor: '#F3F4F6',
                color: '#374151',
                border: '1px solid #D1D5DB',
                borderRadius: '6px',
                padding: '10px 20px',
                fontWeight: 600,
                cursor: isExecuting ? 'not-allowed' : 'pointer'
              }}
            >
              Simulation / Dry Run
            </button>
          </div>
        </div>
      </Card>

      {/* History Table */}
      <Card title="Billing Execution Runs" subtitle="Audit log of all scheduled and on-demand runs">
        {loading ? (
          <div>Loading runs...</div>
        ) : runs.length === 0 ? (
          <div style={{ textAlign: 'center', padding: '32px', color: '#6B7280' }}>No billing runs found. Click above to trigger your first run.</div>
        ) : (
          <table style={{ width: '100%', borderCollapse: 'collapse', textAlign: 'left' }}>
            <thead>
              <tr style={{ borderBottom: '2px solid #E5E7EB', color: '#4B5563', fontSize: '13px' }}>
                <th style={{ padding: '10px 12px' }}>Run ID</th>
                <th style={{ padding: '10px 12px' }}>Started At</th>
                <th style={{ padding: '10px 12px' }}>Triggered By</th>
                <th style={{ padding: '10px 12px' }}>Status</th>
                <th style={{ padding: '10px 12px' }}>Checked</th>
                <th style={{ padding: '10px 12px' }}>Created</th>
                <th style={{ padding: '10px 12px' }}>Failures</th>
                <th style={{ padding: '10px 12px' }}>Action</th>
              </tr>
            </thead>
            <tbody>
              {runs.map((r) => (
                <tr key={r.id} style={{ borderBottom: '1px solid #F3F4F6', fontSize: '14px' }}>
                  <td style={{ padding: '12px', fontFamily: 'monospace', color: '#4B5563' }}>{r.id.substring(0, 8)}...</td>
                  <td style={{ padding: '12px' }}>{new Date(r.started_at).toLocaleString()}</td>
                  <td style={{ padding: '12px' }}>
                    <Badge status={r.triggered_by} variant="neutral" />
                  </td>
                  <td style={{ padding: '12px' }}>
                    <Badge status={r.status} />
                  </td>
                  <td style={{ padding: '12px' }}>{r.subscriptions_checked}</td>
                  <td style={{ padding: '12px', fontWeight: 600, color: '#065F46' }}>{r.invoices_created}</td>
                  <td style={{ padding: '12px', color: r.failures > 0 ? '#DC2626' : '#6B7280' }}>{r.failures}</td>
                  <td style={{ padding: '12px' }}>
                    <button
                      onClick={() => openRunDetails(r.id)}
                      style={{
                        padding: '4px 10px',
                        background: '#EFF6FF',
                        color: '#1D4ED8',
                        border: '1px solid #BFDBFE',
                        borderRadius: '4px',
                        cursor: 'pointer',
                        fontSize: '12px',
                        fontWeight: 600
                      }}
                    >
                      View Items
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </Card>

      {/* Run Items Modal */}
      <Modal isOpen={!!selectedRun} onClose={() => setSelectedRun(null)} title={`Billing Run Details (${selectedRun?.id.substring(0, 8)})`} width="750px">
        {selectedRun && (
          <div>
            <div style={{ display: 'grid', gridTemplateColumns: 'repeat(4, 1fr)', gap: '12px', marginBottom: '20px' }}>
              <div>
                <span style={{ fontSize: '12px', color: '#6B7280' }}>Status</span>
                <div><Badge status={selectedRun.status} /></div>
              </div>
              <div>
                <span style={{ fontSize: '12px', color: '#6B7280' }}>Checked</span>
                <div style={{ fontWeight: 600 }}>{selectedRun.subscriptions_checked}</div>
              </div>
              <div>
                <span style={{ fontSize: '12px', color: '#6B7280' }}>Invoices Created</span>
                <div style={{ fontWeight: 600, color: '#059669' }}>{selectedRun.invoices_created}</div>
              </div>
              <div>
                <span style={{ fontSize: '12px', color: '#6B7280' }}>Failures</span>
                <div style={{ fontWeight: 600, color: selectedRun.failures > 0 ? '#DC2626' : '#6B7280' }}>{selectedRun.failures}</div>
              </div>
            </div>

            <h4 style={{ margin: '0 0 10px 0', fontSize: '15px' }}>Itemized Execution Results</h4>
            {selectedRun.items && selectedRun.items.length > 0 ? (
              <table style={{ width: '100%', borderCollapse: 'collapse', textAlign: 'left', fontSize: '13px' }}>
                <thead>
                  <tr style={{ borderBottom: '2px solid #E5E7EB', color: '#6B7280' }}>
                    <th style={{ padding: '8px' }}>Subscription</th>
                    <th style={{ padding: '8px' }}>Period</th>
                    <th style={{ padding: '8px' }}>Result</th>
                    <th style={{ padding: '8px' }}>Invoice</th>
                    <th style={{ padding: '8px' }}>Notes / Error</th>
                  </tr>
                </thead>
                <tbody>
                  {selectedRun.items.map((item) => (
                    <tr key={item.id} style={{ borderBottom: '1px solid #F3F4F6' }}>
                      <td style={{ padding: '8px', fontFamily: 'monospace' }}>{item.subscription_id}</td>
                      <td style={{ padding: '8px' }}>{item.period_start} to {item.period_end}</td>
                      <td style={{ padding: '8px' }}>
                        <Badge status={item.result} />
                      </td>
                      <td style={{ padding: '8px', fontFamily: 'monospace' }}>
                        {item.invoice_id ? item.invoice_id.substring(0, 8) : '-'}
                      </td>
                      <td style={{ padding: '8px', color: item.error ? '#DC2626' : '#6B7280' }}>
                        {item.error || 'Clean execution'}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            ) : (
              <div style={{ textAlign: 'center', padding: '20px', color: '#6B7280' }}>No itemized rows recorded for this run.</div>
            )}
          </div>
        )}
      </Modal>
    </div>
  );
};
